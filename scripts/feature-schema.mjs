import { writeFileSync } from "node:fs";
import { featureSchemas } from "../src/lib/feature-types.ts";

function schema(z) {
  const d = z._def;
  if (d.typeName === "ZodEffects") return schema(d.schema);
  if (d.typeName === "ZodOptional") return schema(d.innerType);
  if (d.typeName === "ZodObject") {
    const shape = d.shape();
    return {
      type: "object",
      properties: Object.fromEntries(Object.entries(shape).map(([k, v]) => [k, schema(v)])),
      required: Object.entries(shape)
        .filter(([, v]) => !v.isOptional())
        .map(([k]) => k),
      strict: true,
    };
  }
  if (d.typeName === "ZodRecord") return { type: "object", values: schema(d.valueType) };
  if (d.typeName === "ZodArray")
    return {
      type: "array",
      items: schema(d.type),
      min: d.minLength?.value ?? 0,
      max: d.maxLength?.value ?? 1000,
    };
  if (d.typeName === "ZodEnum") return { type: "string", enum: d.values };
  if (d.typeName === "ZodBoolean") return { type: "boolean" };
  if (d.typeName === "ZodNumber")
    return {
      type: "number",
      min: d.checks.find((c) => c.kind === "min")?.value,
      exclusiveMin: d.checks.find((c) => c.kind === "min")?.inclusive === false,
      max: d.checks.find((c) => c.kind === "max")?.value,
      integer: d.checks.some((c) => c.kind === "int"),
    };
  if (d.typeName === "ZodString")
    return {
      type: "string",
      min: d.checks.find((c) => c.kind === "min")?.value,
      max: d.checks.find((c) => c.kind === "max")?.value,
      trim: d.checks.some((c) => c.kind === "trim"),
      format: d.checks.find((c) => ["date", "datetime", "uuid", "url"].includes(c.kind))?.kind,
      pattern: d.checks.find((c) => c.kind === "regex")?.regex.source,
    };
  throw new Error(`Unsupported schema ${d.typeName}`);
}
const specs = Object.fromEntries(
  Object.entries(featureSchemas).map(([kind, z]) => [kind, schema(z)]),
);
const sql = `-- Generated by scripts/feature-schema.mjs from strict application schemas.\nCREATE OR REPLACE FUNCTION public.kinra_feature_schemas() RETURNS jsonb LANGUAGE sql IMMUTABLE SET search_path=public AS $schemas$ SELECT $json$${JSON.stringify(specs)}$json$::jsonb $schemas$;\nREVOKE ALL ON FUNCTION public.kinra_feature_schemas() FROM PUBLIC;\nGRANT EXECUTE ON FUNCTION public.kinra_feature_schemas() TO authenticated, service_role;\n`;
writeFileSync(new URL("../drizzle/migrations/0004_feature_schemas.sql", import.meta.url), sql);
console.log(`Generated database schemas for ${Object.keys(specs).length} feature kinds.`);
